@dataclass(frozen=True)
class Sql:
    value: str


def ident(kind: str, number: int | str) -> str:
    return str(uuid5(NAMESPACE, f"{kind}:{number}"))


def when(minutes: int = 0) -> Sql:
    return Sql(f"CURRENT_TIMESTAMP + INTERVAL '{minutes} minutes'")


def literal(value: object) -> str:
    if isinstance(value, Sql):
        return value.value
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "TRUE" if value else "FALSE"
    if isinstance(value, (int, float, Decimal)):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def jsonb(value: object) -> Sql:
    return Sql(literal(json.dumps(value, ensure_ascii=False, separators=(",", ":"))) + "::jsonb")



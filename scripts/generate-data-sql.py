class Seed:
    def __init__(self) -> None:
        self.rows: dict[str, list[dict[str, object]]] = defaultdict(list)
        self.order: list[str] = []

    def add(self, table: str, **values: object) -> None:
        if table not in self.order:
            self.order.append(table)
        self.rows[table].append(values)

    def write(self) -> None:
        lines = [
            "-- ============================================================================",
            "-- TutorHub Production-Grade Realistic Dataset (Data.sql)",
            "-- Auto-generated by AI with rich domain context, authentic Vietnamese profiles,",
            "-- coherent financial balances, full reviews, sessions, and wishlist items.",
            "-- All accounts can log in with password: Test@123",
            "-- ============================================================================",
            "BEGIN;",
            "SET LOCAL client_encoding = 'UTF8';",
            "TRUNCATE TABLE " + ", ".join(f'"{table}"' for table in TABLES) + " RESTART IDENTITY CASCADE;",
        ]

        for table in INSERT_ORDER:
            rows = self.rows[table]
            if not rows:
                continue
            columns = list(rows[0])
            header = ", ".join(f'"{column}"' for column in columns)
            lines.append(f"\n-- {table}: {len(rows)} records")
            lines.append(f'INSERT INTO "{table}" ({header}) VALUES')
            for i, row in enumerate(rows):
                suffix = ";" if i == len(rows) - 1 else ","
                lines.append("    (" + ", ".join(literal(row.get(column)) for column in columns) + ")" + suffix)

        lines.extend([
            "\nCOMMIT;",
            "",
        ])

        OUTPUT.write_text("\n".join(lines), encoding="utf-8")
        print(f"Successfully generated {OUTPUT} with:")
        for t in INSERT_ORDER:
            if self.rows[t]:
                print(f"  - {t}: {len(self.rows[t])} rows")


